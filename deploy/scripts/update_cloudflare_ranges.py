#!/usr/bin/env python3
"""Regenerate the gateway's list of Cloudflare edge address ranges.

The gateway's cloudflare mode (EVERGARDEN_GATEWAY_REAL_IP=cloudflare) trusts
CF-Connecting-IP only from these ranges. Cloudflare publishes them at
https://www.cloudflare.com/ips/ and changes them rarely; run this script from
time to time (or when Cloudflare announces a change), review the diff, and
restart the gateway:

    python3 deploy/scripts/update_cloudflare_ranges.py          # fetch and rewrite
    python3 deploy/scripts/update_cloudflare_ranges.py --check  # exit 1 if stale

Standard library only. ``--ipv4-file`` / ``--ipv6-file`` read saved copies of
the two lists instead of fetching them.
"""

from __future__ import annotations

import argparse
import datetime as dt
import ipaddress
import sys
import urllib.request
from collections.abc import Iterable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "deploy" / "nginx" / "real-ip" / "cloudflare-ranges.conf"
SOURCES = {
    4: "https://www.cloudflare.com/ips-v4",
    6: "https://www.cloudflare.com/ips-v6",
}
MAX_BYTES = 64 * 1024


class RangesError(ValueError):
    """The published list is not what this script expects."""


def parse_ranges(text: str, version: int) -> list[str]:
    """Return the CIDRs of one published list, validated and in published order."""
    networks: list[str] = []
    for line in text.splitlines():
        entry = line.strip()
        if not entry:
            continue
        try:
            network = ipaddress.ip_network(entry, strict=True)
        except ValueError as exc:
            raise RangesError(f"not a CIDR: {entry!r}") from exc
        if network.version != version:
            raise RangesError(f"{entry} is not an IPv{version} range")
        if network.prefixlen < 8:
            raise RangesError(f"{entry} is implausibly large for an edge range")
        if str(network) not in networks:
            networks.append(str(network))
    if not networks:
        raise RangesError(f"the IPv{version} list is empty")
    return networks


def render(ipv4: Iterable[str], ipv6: Iterable[str], fetched: dt.date) -> str:
    lines = [
        "# Cloudflare edge address ranges for the gateway's cloudflare mode, included",
        "# inside a geo block by cloudflare.conf. Generated by",
        "# deploy/scripts/update_cloudflare_ranges.py; do not edit by hand.",
        f"# Source: {SOURCES[4]} and {SOURCES[6]}",
        f"# Fetched: {fetched.isoformat()}",
    ]
    lines += [f"{network} 1;" for network in ipv4]
    lines += [f"{network} 1;" for network in ipv6]
    return "\n".join(lines) + "\n"


def fetch(url: str) -> str:
    # Only the two fixed https:// SOURCES are ever opened.
    request = urllib.request.Request(url, headers={"User-Agent": "evergarden-ranges/1"})  # noqa: S310
    with urllib.request.urlopen(request, timeout=20) as response:  # noqa: S310
        body = response.read(MAX_BYTES + 1)
    if len(body) > MAX_BYTES:
        raise RangesError(f"{url} returned more than {MAX_BYTES} bytes")
    return body.decode("ascii")


def ranges_in(document: str) -> list[str]:
    """The ranges listed in an existing generated file (comments ignored)."""
    return [
        line.split()[0]
        for line in document.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the ranges changed")
    parser.add_argument("--ipv4-file", type=Path, help="read the IPv4 list from this file")
    parser.add_argument("--ipv6-file", type=Path, help="read the IPv6 list from this file")
    parser.add_argument("--output", type=Path, default=OUTPUT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        texts = {
            4: args.ipv4_file.read_text("ascii") if args.ipv4_file else fetch(SOURCES[4]),
            6: args.ipv6_file.read_text("ascii") if args.ipv6_file else fetch(SOURCES[6]),
        }
        ipv4 = parse_ranges(texts[4], 4)
        ipv6 = parse_ranges(texts[6], 6)
    except (OSError, UnicodeDecodeError, RangesError) as exc:
        print(f"update_cloudflare_ranges: {exc}", file=sys.stderr)
        return 2
    current = args.output.read_text("utf-8") if args.output.exists() else ""
    unchanged = ranges_in(current) == ipv4 + ipv6
    if args.check:
        if not unchanged:
            print(f"{args.output} is stale; run this script without --check", file=sys.stderr)
            return 1
        print("Cloudflare ranges are current")
        return 0
    if unchanged:
        print("Cloudflare ranges unchanged; file left as it is")
        return 0
    today = dt.datetime.now(dt.timezone.utc).date()  # noqa: UP017 - runs on older Pythons too
    args.output.write_text(render(ipv4, ipv6, today), "utf-8")
    print(f"wrote {len(ipv4)} IPv4 and {len(ipv6)} IPv6 ranges to {args.output}")
    print("Restart the gateway to apply them: docker compose restart gateway")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
